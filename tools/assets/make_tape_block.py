"""Кассета в мире (0.9, пункт 16): 3D-модель VHS-кассеты, лежащей плашмя, текстуры 32x32.

Usage: python -I tools/assets/make_tape_block.py <repo root>
Свои текстуры на помощниках make_blocks.py. Модель в границах коллизии TapeBlock: x3..13 y0..2 z5..11.
Верх: потёртая чёрная пластмасса, бумажная наклейка цвета кости с выцветшей надписью от руки,
два окошка с тёмными бобинами. Бока: рёбра корпуса и окно ленты спереди. Без ярких цветов.
"""
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
import make_blocks as mb  # noqa: E402

N = mb.N


def tex_shell():
    r = mb.rng(701)
    img = mb.base((26, 25, 24), r, var=0.12, grain=0.06)
    img = mb.scratches(img, r, 9)
    img = mb.grime(img, r, 0.2, streaks=False)
    for y in range(4, N, 6):
        img[y, :] = np.clip(img[y, :] * 1.5, 0, 1)  # рёбра корпуса
    return mb.edge_darken(img, 1, 0.7)


def tex_top():
    r = mb.rng(702)
    img = tex_shell()
    # Наклейка (кость C4BCAA, пожелтевшая) в верхней половине.
    img = mb.rect(img, 3, 3, 29, 13, (180, 170, 146))
    img = mb.grime(img, r, 0.25, streaks=False)
    # «Надпись от руки»: несколько неровных штрихов цвета сажи.
    for row, (x0, x1) in ((6, (6, 22)), (9, (6, 17))):
        for x in range(x0, x1):
            if r.random() < 0.8:
                y = row + int(round(np.sin(x * 0.9) * 0.6))
                img[y, x] = np.array([0.20, 0.18, 0.16])
    # Две бобины в окошке под наклейкой.
    img = mb.rect(img, 6, 16, 26, 26, (14, 14, 14))
    for cx in (11, 21):
        img = mb.circle(img, cx, 21, 4, (40, 34, 30), ring=(70, 66, 60))
        img = mb.circle(img, cx, 21, 1, (120, 116, 108))
    img = mb.rect(img, 6, 16, 26, 26, (60, 60, 60), alpha=0.18)  # мутное стекло окна
    return np.clip(img, 0, 1)


def tex_front():
    r = mb.rng(703)
    img = tex_shell()
    # Крышка ленты: тёмная полоса с бликом.
    img = mb.rect(img, 2, 8, 30, 24, (12, 12, 12))
    img[9, 2:30] = np.clip(img[9, 2:30] * 3.0 + 0.05, 0, 1)
    return np.clip(img, 0, 1)


TEXTURES = {"tape_shell": tex_shell, "tape_top": tex_top, "tape_front": tex_front}


def model():
    els = [
        mb.el("body", (3, 0, 5), (13, 1.5, 11), "shell", full=("up",), up="top", north="front", cull=("down",)),
        mb.el("hub lip", (3.5, 1.5, 5.5), (12.5, 1.75, 6), "shell"),
    ]
    tex = {"particle": "tape_shell", "shell": "tape_shell", "top": "tape_top", "front": "tape_front"}
    rot = [30, 225, 0]
    m = mb.model(tex, els, mb.display(rot, mb.centre_translation(rot, 0.625, (8, 1, 8))), ao=True)
    m["credit"] = "Bodycam Horror, generated by tools/assets/make_tape_block.py"
    return m


def main():
    root = Path(sys.argv[1]).resolve()
    assets = root / "src/main/resources/assets/bodycamhorror"
    for name, fn in TEXTURES.items():
        img = (np.clip(fn(), 0, 1) * 255).round().astype(np.uint8)
        Image.fromarray(img, "RGB").save(assets / "textures/block" / f"{name}.png", optimize=True)
        print("texture", name)
    (assets / "models/block/tape_block.json").write_text(json.dumps(model(), indent=2) + "\n", encoding="utf-8")
    bs = {"variants": {f"facing={f}": {"model": "bodycamhorror:block/tape_block", **({"y": y} if y else {})}
                       for f, y in (("north", 0), ("east", 90), ("south", 180), ("west", 270))}}
    (assets / "blockstates/tape_block.json").write_text(json.dumps(bs, indent=2) + "\n", encoding="utf-8")
    print("model and blockstate")


if __name__ == "__main__":
    main()
