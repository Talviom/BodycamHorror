"""Аварийная лампа (0.9): текстуры 32x32 и модели, потолочная и напольная, горит и погасла.

Usage: python -I tools/assets/make_emergency.py <repo root>
Берёт помощники из make_blocks.py (тот же шум, грязь, ржавчина), но сам make_blocks.py не перезапускает,
чтобы не трогать готовые текстуры ламп, щитка и генератора.

Промышленная аварийная лампа: стальная плита, тёмно-красный стеклянный колпак в решётке.
Красный приглушённый, цвета запёкшейся крови, без неона. Горит тускло (свет 5), только когда генератор выключен.
Потолочная модель: x5..11 y10..16 z5..11. Напольная: то же, отражённое по высоте (y0..6).
"""
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
import make_blocks as mb  # noqa: E402

N = mb.N


def tex_glass_on():
    r = mb.rng(601)
    yy, xx = np.mgrid[:N, :N]
    d = np.sqrt((xx - N / 2 + 0.5) ** 2 + (yy - N / 2 + 0.5) ** 2) / (N / 2)
    core = np.array([0.80, 0.20, 0.14])   # горячая середина колпака
    rim = np.array([0.40, 0.06, 0.05])    # край, ближе к запёкшейся крови 7A1612
    k = np.clip(1 - d, 0, 1)[..., None]
    img = rim + (core - rim) * k ** 1.3
    # Рифление стекла: горизонтальные полосы, и неровная пыль на нём.
    img = img * (0.9 + 0.1 * np.sin(np.arange(N) * 1.6))[:, None, None]
    img = img * (1 - 0.25 * mb.value_noise(r, 5)[..., None] * r.random((N, N, 1)))
    return np.clip(img, 0, 1)


def tex_glass_off():
    r = mb.rng(602)
    img = mb.base((52, 24, 22), r, var=0.08, grain=0.05)
    img = img * (0.9 + 0.1 * np.sin(np.arange(N) * 1.6))[:, None, None]
    img = mb.grime(img, r, 0.35, streaks=False)
    img[6:20, 9] = np.clip(img[6:20, 9] * 1.6, 0, 1)  # блик на мёртвом стекле
    return np.clip(img, 0, 1)


def tex_cage():
    r = mb.rng(603)
    img = mb.base((46, 46, 44), r, var=0.1, grain=0.06)
    img = mb.rust(img, r, 0.18)
    img = mb.scratches(img, r, 5)
    return mb.edge_darken(img, 1, 0.6)


def tex_plate():
    r = mb.rng(604)
    img = mb.base((88, 84, 76), r, var=0.07)
    img = mb.grime(img, r, 0.4)
    img = mb.rust(img, r, 0.1)
    # Жёлто-чёрная полоса по краю, выцветшая почти до бурого.
    for x in range(N):
        if (x // 3) % 2 == 0:
            img[:2, x] = img[:2, x] * 0.3 + np.array([0.45, 0.36, 0.12]) * 0.7
            img[-2:, x] = img[-2:, x] * 0.3 + np.array([0.45, 0.36, 0.12]) * 0.7
    img = mb.rivets(img, [(4, 4), (27, 4), (4, 27), (27, 27)])
    return mb.edge_darken(img, 1, 0.6)


TEXTURES = {
    "emergency_glass_on": tex_glass_on,
    "emergency_glass_off": tex_glass_off,
    "emergency_cage": tex_cage,
    "emergency_plate": tex_plate,
}


def flip_y(e):
    """Отражение элемента по высоте (потолочная модель → напольная)."""
    f, t = e["from"], e["to"]
    e["from"] = [f[0], 16 - t[1], f[2]]
    e["to"] = [t[0], 16 - f[1], t[2]]
    faces = e["faces"]
    up, down = faces.pop("up", None), faces.pop("down", None)
    if up:
        faces["down"] = up
        if up.get("cullface") == "up":
            up["cullface"] = "down"
    if down:
        faces["up"] = down
    for face, entry in faces.items():
        entry["uv"] = [round(v, 3) for v in mb.default_uv(face, e["from"], e["to"])] if face not in ("up", "down") else entry["uv"]
    return e


def emergency(lit, floor):
    els = [
        mb.el("plate", (4.5, 15, 4.5), (11.5, 16, 11.5), "plate", cull=("up",)),
        mb.el("collar", (5.5, 14, 5.5), (10.5, 15, 10.5), "cage"),
        mb.el("glass", (6, 10.5, 6), (10, 14, 10), "glass", emissive=lit),
        mb.el("glass tip", (6.75, 10, 6.75), (9.25, 10.5, 9.25), "glass", emissive=lit),
        # Решётка: четыре прута по углам и обод снизу.
        mb.el("bar nw", (5.5, 10.25, 5.5), (6, 14, 6), "cage"),
        mb.el("bar ne", (10, 10.25, 5.5), (10.5, 14, 6), "cage"),
        mb.el("bar sw", (5.5, 10.25, 10), (6, 14, 10.5), "cage"),
        mb.el("bar se", (10, 10.25, 10), (10.5, 14, 10.5), "cage"),
        mb.el("ring n", (5.5, 10, 5.5), (10.5, 10.5, 6), "cage"),
        mb.el("ring s", (5.5, 10, 10), (10.5, 10.5, 10.5), "cage"),
        mb.el("ring w", (5.5, 10, 6), (6, 10.5, 10), "cage"),
        mb.el("ring e", (10, 10, 6), (10.5, 10.5, 10), "cage"),
        mb.el("cross", (7.75, 10, 5.5), (8.25, 10.5, 10.5), "cage"),
    ]
    if floor:
        els = [flip_y(e) for e in els]
    tex = {"particle": "emergency_plate", "plate": "emergency_plate", "cage": "emergency_cage",
           "glass": "emergency_glass_on" if lit else "emergency_glass_off"}
    rot = [30, 225, 0] if floor else [-30, 225, 0]
    centre = (8, 3, 8) if floor else (8, 13, 8)
    m = mb.model(tex, els, mb.display(rot, mb.centre_translation(rot, 0.625, centre)), ao=False)
    m["credit"] = "Bodycam Horror, generated by tools/assets/make_emergency.py"
    return m


MODELS = {
    "emergency_lamp": lambda: emergency(True, False),
    "emergency_lamp_off": lambda: emergency(False, False),
    "emergency_lamp_floor": lambda: emergency(True, True),
    "emergency_lamp_floor_off": lambda: emergency(False, True),
}


def main():
    root = Path(sys.argv[1]).resolve()
    assets = root / "src/main/resources/assets/bodycamhorror"
    tex_dir = assets / "textures/block"
    for name, fn in TEXTURES.items():
        img = (np.clip(fn(), 0, 1) * 255).round().astype(np.uint8)
        Image.fromarray(img, "RGB").save(tex_dir / f"{name}.png", optimize=True)
        print("texture", name)
    mdir = assets / "models/block"
    for name, fn in MODELS.items():
        m = fn()
        for e in m["elements"]:
            for i in range(3):
                assert 0 <= e["from"][i] < e["to"][i] <= 16, f"{name}/{e['name']} out of bounds"
        (mdir / f"{name}.json").write_text(json.dumps(m, indent=2) + "\n", encoding="utf-8")
        print(f"model {name}: {len(m['elements'])} elements")
    (assets / "models/item/emergency_lamp.json").write_text(
        json.dumps({"parent": "bodycamhorror:block/emergency_lamp"}, indent=2) + "\n", encoding="utf-8")
    bs = {"variants": {
        "floor=false,lit=true": {"model": "bodycamhorror:block/emergency_lamp"},
        "floor=false,lit=false": {"model": "bodycamhorror:block/emergency_lamp_off"},
        "floor=true,lit=true": {"model": "bodycamhorror:block/emergency_lamp_floor"},
        "floor=true,lit=false": {"model": "bodycamhorror:block/emergency_lamp_floor_off"},
    }}
    (assets / "blockstates/emergency_lamp.json").write_text(json.dumps(bs, indent=2) + "\n", encoding="utf-8")
    print("blockstate and item model")


if __name__ == "__main__":
    main()
