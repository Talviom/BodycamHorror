package com.talviom.bodycamhorror.horror;

public enum HorrorEvent {
    /** Шаги за спиной, слышит только цель. */
    FOOTSTEPS("footsteps", 5),
    /** Шёпот и гул пещеры, слышит только цель. */
    WHISPER("whisper", 4),
    /** Стук в дверь или скрип рядом, слышит только цель. */
    KNOCK("knock", 3),
    /** Лампы вокруг цели мигают и ненадолго гаснут, видят все. */
    FLICKER("flicker", 4),
    /** Помехи на бодикаме цели. */
    GLITCH("glitch", 3),
    /** Помехи в рации команды цели: часть слов пропадает. */
    RADIO("radio", 2),

    // 0.9 (пункт 15), от лёгких к сложным: звуки, свет, камера, фигуры. Всё без урона, видит и слышит один.
    /** Дыхание прямо за спиной. */
    BREATH("breath", 3),
    /** Шипение кассеты с ложной стороны. */
    TAPE_HISS("tape_hiss", 2),
    /** Хлопок двери или люка рядом. */
    DOOR("door", 3),
    /** Далёкий удар по металлической трубе. */
    METAL("metal", 3),
    /** Далёкий крик. */
    CRY("cry", 2),
    /** В пустой комнате звонит старый телефон, потом снимают трубку и дышат. */
    PHONE("phone", 2),
    /** Скачок напряжения: лампы вокруг гудят, вспыхивают и гаснут на 2-3 с. */
    SURGE("surge", 3),
    /** Волна гаснущих ламп: от дальних к игроку. */
    WAVE("wave", 3),
    /** Сбой времени на часах камеры. */
    TIMECODE("timecode", 2),
    /** Перемотка: плёнку дёргает назад. */
    REWIND("rewind", 2),
    /** Силуэт Жильца в конце коридора. */
    SILHOUETTE("silhouette", 2);

    public final String id;
    public final int weight;

    HorrorEvent(String id, int weight) {
        this.id = id;
        this.weight = weight;
    }
}
